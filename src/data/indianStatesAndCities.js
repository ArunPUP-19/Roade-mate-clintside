export const INDIAN_STATES = Object.keys(INDIAN_STATES_AND_CITIES);

export function getCitiesForState(state) {
  if (!state) return [];
  return INDIAN_STATES_AND_CITIES[state] || [];
}

export function matchStateName(rawState) {
  if (!rawState) return '';
  const normalized = rawState.trim().toLowerCase();
  
  // Direct match
  const found = INDIAN_STATES.find(s => s.toLowerCase() === normalized);
  if (found) return found;

  // Substring match
  const partial = INDIAN_STATES.find(s => 
    normalized.includes(s.toLowerCase()) || s.toLowerCase().includes(normalized)
  );
  return partial || '';
}
